"""
PDF review-comment extraction.

Reads review comments out of a PDF and returns them as flat records for the
Excel exporter and the web UI.

Passes, per page
----------------
1.  Native annotations: Sticky Notes, their Replies, and FreeText.
2.  Coloured text that exists as real page text (flattened comments).
2B. Scanned pages, read with OCR:
      - typed comment sheets  -> whole page, one record per numbered point
      - drawings / forms      -> coloured ink only (red, orange, gold,
                                 green, blue)
2C. Callout boxes drawn as plain shapes (filled box + coloured border),
    read directly or with OCR.

After all pages, duplicates are removed and record IDs are renumbered.
"""

from datetime import datetime
import re
import math

import pymupdf

import ocr_scanned

# ============================================================
# CONFIGURATION
# ============================================================

# Native annotation types that we want.
#
# "Text" is the PDF name for a Sticky Note / comment icon (the small speech
# bubble reviewers drop on a drawing). The other markup types are kept when
# the reviewer typed a comment on them.
#
# Exported to Excel:
#     Sticky Note, Reply      (PDF type "Text")
#     FreeText                (text box / callout / typewriter)
#
# Native Highlight, Underline, Strikeout, Squiggly, Stamp, Caret,
# File attachment and Ink (pen) annotations are NOT exported.
# To bring one back, add its PDF type name to this set.
ALLOWED_ANNOTATION_TYPES = {
    "FreeText",
    "Text",
}

# Annotations that draw no text of their own (the page text under a
# highlight is real page content and may be a flattened comment).
TRANSPARENT_ANNOTATION_TYPES = {
    "Highlight",
    "Underline",
    "StrikeOut",
    "Squiggly",
    "Link",
    "Popup",
}

# Pen (Ink) strokes read with OCR. Not exported.
EXTRACT_PEN_MARKS = False

# Flattened highlighter / cloud regions read with OCR ("Highlight (OCR)").
# Not exported.
EXTRACT_HIGHLIGHT_REGIONS = False

# Drawing shapes (rectangle, oval, line, cloud...). Reviewers use these to
# point at something, and the text stored on them is usually just a copy of
# the drawing text underneath ("162-PSV-222A"), so they are NOT exported.
# Set INCLUDE_SHAPE_COMMENTS = True to export shapes that carry typed text.
INCLUDE_SHAPE_COMMENTS = False

SHAPE_TYPES = {"Square", "Circle", "Line", "Polygon", "PolyLine"}

if INCLUDE_SHAPE_COMMENTS:
    ALLOWED_ANNOTATION_TYPES |= SHAPE_TYPES

# Marks that are only exported when they carry a typed comment.
COMMENT_ONLY_TYPES = {"Caret", "FileAttachment"} | SHAPE_TYPES

# AutoCAD's "Export to PDF" stores every piece of drawing text as an
# invisible rectangle annotation (author "AutoCAD SHX Text") so the text
# stays searchable. These are drawing content, never review comments.
CAD_TEXT_AUTHORS = ("autocad shx text", "autocad shx")

# PDF annotation flags (PDF spec, table 165)
FLAG_INVISIBLE = 1
FLAG_HIDDEN = 2
FLAG_PRINT = 4
FLAG_NOVIEW = 32
FLAG_READONLY = 64


def is_cad_or_hidden_annotation(annotation, info):
    """True for annotations that are not review comments a person made."""

    author = str(info.get("title") or info.get("author") or "").strip().lower()
    subject = str(info.get("subject") or "").strip().lower()

    if author.startswith(CAD_TEXT_AUTHORS) or subject.startswith(CAD_TEXT_AUTHORS):
        return True

    try:
        flags = int(annotation.flags)
    except Exception:
        return False

    # Hidden from view.
    if flags & (FLAG_INVISIBLE | FLAG_HIDDEN | FLAG_NOVIEW):
        return True

    # Locked AND not printed: generated by the authoring software
    # (CAD text, form scaffolding), not added by a reviewer.
    if flags & FLAG_READONLY and not flags & FLAG_PRINT:
        return True

    return False

# Text-markup types whose underlying page text is read (like Highlight).
TEXT_MARKUP_TYPES = {"Highlight", "Underline", "StrikeOut", "Squiggly"}

# Friendly names shown in the Excel "Type" column.
ANNOTATION_TYPE_LABELS = {
    "Text": "Sticky Note",
    "StrikeOut": "Strikethrough",
    "Square": "Rectangle",
    "Circle": "Oval",
    "PolyLine": "Polyline",
    "Caret": "Insert Text",
}

# Used for detecting coloured / flattened review text.
MIN_COLOR_SATURATION = 0.25
MIN_COLOR_BRIGHTNESS = 0.18

# Used when grouping coloured page text.
TEXT_LINE_VERTICAL_TOLERANCE = 5.0
TEXT_GROUP_DISTANCE = 25.0


# ============================================================
# PDF DATE PARSER
# ============================================================


def parse_pdf_datetime(value):
    """
    Convert PDF date:

        D:YYYYMMDDHHMMSS

    Into:

        DD-MM-YYYY
        HH:MM:SS
    """

    if not value:
        return None, None

    try:
        value = str(value)

        if value.startswith("D:"):
            value = value[2:]

        match = re.match(r"(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})", value)

        if not match:
            return None, None

        year, month, day, hour, minute, second = match.groups()

        dt = datetime(
            int(year), int(month), int(day), int(hour), int(minute), int(second)
        )

        return (dt.strftime("%d-%m-%Y"), dt.strftime("%H:%M:%S"))

    except Exception:
        return None, None


# ============================================================
# TEXT NORMALIZATION
# ============================================================


def normalize_text(value):
    """
    Normalize text for duplicate comparison.
    """

    if not value:
        return ""

    value = str(value)

    value = re.sub(r"\s+", " ", value)

    return value.strip().lower()


# ============================================================
# COLOR HELPERS
# ============================================================


def int_to_rgb(color_value):
    """
    Convert PyMuPDF integer colour to RGB 0-1 values.
    """

    try:
        color_value = int(color_value)

        red = (color_value >> 16) & 255
        green = (color_value >> 8) & 255
        blue = color_value & 255

        return (red / 255.0, green / 255.0, blue / 255.0)

    except Exception:
        return 0.0, 0.0, 0.0


def get_color_properties(rgb):
    """
    Return brightness and saturation.
    """

    r, g, b = rgb

    maximum = max(r, g, b)
    minimum = min(r, g, b)

    brightness = maximum

    if maximum == 0:
        saturation = 0
    else:
        saturation = (maximum - minimum) / maximum

    return brightness, saturation


def is_review_color(color_value):
    """
    Detect coloured review text: every colour except black, grey and white.
    """

    try:
        r, g, b = int_to_rgb(color_value)

        brightness, saturation = get_color_properties((r, g, b))

        if brightness < MIN_COLOR_BRIGHTNESS:
            return False

        # Any real colour counts (red, orange, yellow, green, blue, violet,
        # pink, brown...). Only black, grey and white are excluded: they
        # have no saturation, and black / near-black (#231F20 body text)
        # is also below the brightness limit.
        return saturation >= MIN_COLOR_SATURATION

    except Exception:
        return False


# ============================================================
# RECTANGLE HELPERS
# ============================================================


def bbox_to_rect(bbox):

    try:
        if not bbox or len(bbox) < 4:
            return None

        return pymupdf.Rect(
            float(bbox[0]), float(bbox[1]), float(bbox[2]), float(bbox[3])
        )

    except Exception:
        return None


def rect_center(rect):

    if rect is None:
        return None

    return ((rect.x0 + rect.x1) / 2, (rect.y0 + rect.y1) / 2)


def rect_distance(rect1, rect2):

    if rect1 is None or rect2 is None:
        return float("inf")

    center1 = rect_center(rect1)
    center2 = rect_center(rect2)

    if center1 is None or center2 is None:
        return float("inf")

    return math.sqrt((center1[0] - center2[0]) ** 2 + (center1[1] - center2[1]) ** 2)


def rectangles_overlap(rect1, rect2):

    if rect1 is None or rect2 is None:
        return False

    try:

        intersection = rect1 & rect2

        return intersection.width > 0 and intersection.height > 0

    except Exception:
        return False


# ============================================================
# INTERSECTION AREA
# ============================================================


def rectangle_intersection_ratio(word_rect, highlight_rect):
    """
    Calculate how much of a word rectangle intersects
    with a highlight rectangle.

    This is much safer than using only get_textbox().
    """

    try:

        intersection = word_rect & highlight_rect

        if intersection.width <= 0 or intersection.height <= 0:
            return 0.0

        word_area = word_rect.width * word_rect.height

        if word_area <= 0:
            return 0.0

        intersection_area = intersection.width * intersection.height

        return intersection_area / word_area

    except Exception:
        return 0.0


# ============================================================
# DUPLICATE CHECK
# ============================================================


def is_duplicate_record(existing_records, page_number, text, rect=None):

    normalized_new_text = normalize_text(text)

    if not normalized_new_text:
        return False

    for existing in existing_records:

        if existing.get("page_number") != page_number:
            continue

        existing_text = normalize_text(existing.get("text"))

        if existing_text != normalized_new_text:
            continue

        existing_rect = existing.get("_rect")

        # If position isn't available,
        # same page + same text = duplicate.
        if existing_rect is None or rect is None:
            return True

        if rectangles_overlap(existing_rect, rect):
            return True

        distance = rect_distance(existing_rect, rect)

        if distance <= 15:
            return True

    return False


# ============================================================
# HIGHLIGHT RECTANGLES
# ============================================================


def get_highlight_rectangles(annotation):
    """
    Convert Highlight vertices into rectangles.

    PDF highlights normally contain four points per quad.
    """

    rectangles = []

    try:

        vertices = annotation.vertices

        if not vertices:
            return rectangles

        for i in range(0, len(vertices), 4):

            points = vertices[i : i + 4]

            if len(points) < 4:
                continue

            xs = [point.x for point in points]

            ys = [point.y for point in points]

            rect = pymupdf.Rect(min(xs), min(ys), max(xs), max(ys))

            rectangles.append(rect)

    except Exception:

        pass

    return rectangles


# ============================================================
# EXTRACT WORDS UNDER HIGHLIGHT
# ============================================================


def extract_highlight_text(page, annotation):
    """
    Extract the actual text underneath a Highlight annotation.

    Supports annotation.vertices returned as:
      - pymupdf.Point objects
      - (x, y) tuples / lists
    """

    try:
        vertices = annotation.vertices

        if not vertices:
            return ""

        # ====================================================
        # HELPER: GET X / Y FROM VERTEX
        # ====================================================

        def get_xy(point):
            """
            PyMuPDF versions may return vertices either as:

                Point(x, y)

            or:

                (x, y)
            """

            if hasattr(point, "x") and hasattr(point, "y"):
                return float(point.x), float(point.y)

            if isinstance(point, (tuple, list)) and len(point) >= 2:
                return float(point[0]), float(point[1])

            raise ValueError(f"Unsupported vertex format: {point}")

        # ====================================================
        # CREATE HIGHLIGHT RECTANGLES
        # ====================================================

        highlight_rects = []

        for i in range(0, len(vertices), 4):

            points = vertices[i : i + 4]

            if len(points) < 4:
                continue

            xy_points = [get_xy(point) for point in points]

            xs = [point[0] for point in xy_points]

            ys = [point[1] for point in xy_points]

            rect = pymupdf.Rect(min(xs), min(ys), max(xs), max(ys))

            # Slight expansion helps with text whose bounding
            # box extends slightly outside the highlight.
            expanded_rect = pymupdf.Rect(
                rect.x0 - 2, rect.y0 - 2, rect.x1 + 2, rect.y1 + 2
            )

            highlight_rects.append(expanded_rect)

        if not highlight_rects:

            return ""

        # ====================================================
        # GET PAGE WORDS
        # ====================================================

        words = page.get_text("words", sort=True)

        matched_words = []

        # ====================================================
        # MATCH WORDS TO HIGHLIGHT
        # ====================================================

        for word in words:

            if len(word) < 5:
                continue

            word_text = str(word[4]).strip()

            if not word_text:
                continue

            word_rect = pymupdf.Rect(
                float(word[0]), float(word[1]), float(word[2]), float(word[3])
            )

            # -----------------------------------------------
            # Calculate word area
            # -----------------------------------------------

            word_area = word_rect.width * word_rect.height

            if word_area <= 0:
                continue

            matched = False

            for highlight_rect in highlight_rects:

                intersection = word_rect & highlight_rect

                if intersection.width <= 0 or intersection.height <= 0:
                    continue

                intersection_area = intersection.width * intersection.height

                overlap_ratio = intersection_area / word_area

                # -------------------------------------------
                # Require 35% of the word to overlap.
                #
                # Engineering drawing highlights are often
                # slightly smaller than the text bounding box.
                # -------------------------------------------

                if overlap_ratio >= 0.35:

                    matched = True
                    break

            if not matched:
                continue

            matched_words.append(
                {
                    "text": word_text,
                    "x0": float(word[0]),
                    "y0": float(word[1]),
                    "x1": float(word[2]),
                    "y1": float(word[3]),
                    "block": word[5] if len(word) > 5 else 0,
                    "line": word[6] if len(word) > 6 else 0,
                    "word": word[7] if len(word) > 7 else 0,
                }
            )

        # ====================================================
        # NO MATCHES -> CLIP FALLBACK
        # ====================================================

        if not matched_words:

            fallback_parts = []

            for rect in highlight_rects:

                try:

                    clipped_text = page.get_text("text", clip=rect, sort=True)

                    clipped_text = re.sub(r"\s+", " ", clipped_text).strip()

                    if clipped_text:
                        fallback_parts.append(clipped_text)

                except Exception:

                    pass

            result = " ".join(fallback_parts).strip()

            return result

        # ====================================================
        # SORT MATCHED WORDS
        # ====================================================

        matched_words.sort(
            key=lambda item: (
                item["block"],
                item["line"],
                item["word"],
                item["y0"],
                item["x0"],
            )
        )

        # ====================================================
        # REMOVE DUPLICATE WORDS
        # ====================================================

        unique_words = []

        seen = set()

        for item in matched_words:

            key = (
                round(item["x0"], 2),
                round(item["y0"], 2),
                round(item["x1"], 2),
                round(item["y1"], 2),
                item["text"],
            )

            if key in seen:
                continue

            seen.add(key)

            unique_words.append(item["text"])

        # ====================================================
        # FINAL TEXT
        # ====================================================

        result = " ".join(unique_words)

        result = re.sub(r"\s+", " ", result).strip()

        return result

    except Exception:

        return ""


# ============================================================
# GET COLOURED PAGE TEXT
# ============================================================


def get_colored_text_spans(page):
    """
    Find red/orange/yellow text that exists as normal
    PDF page content.
    """

    spans = []

    # Hyperlinks are blue too: text under a link is not a comment.
    try:
        link_rects = [pymupdf.Rect(link["from"]) for link in page.get_links()]
    except Exception:
        link_rects = []

    try:

        page_dict = page.get_text("dict")

        blocks = page_dict.get("blocks", [])

        for block in blocks:

            if block.get("type") != 0:
                continue

            for line in block.get("lines", []):

                for span in line.get("spans", []):

                    text = (span.get("text", "") or "").strip()

                    if not text:
                        continue

                    color = span.get("color", 0)

                    if not is_review_color(color):
                        continue

                    rect = bbox_to_rect(span.get("bbox"))

                    if rect is None:
                        continue

                    if any(rectangles_overlap(rect, link) for link in link_rects):
                        continue

                    spans.append(
                        {
                            "text": text,
                            "rect": rect,
                            "color": color,
                            "size": span.get("size"),
                            "font": span.get("font"),
                        }
                    )

    except Exception:

        pass

    return spans


# ============================================================
# GROUP COLOURED TEXT
# ============================================================


def group_colored_spans(spans):
    """
    Combine neighbouring coloured spans into comments.
    """

    if not spans:
        return []

    spans = sorted(spans, key=lambda item: (round(item["rect"].y0, 1), item["rect"].x0))

    groups = []

    for span in spans:

        added = False

        for group in groups:

            group_rect = group["rect"]

            span_rect = span["rect"]

            # Two comments in different colours are different comments
            # (a violet remark next to the red "Internal" footer label).
            if span.get("color") != group.get("color"):
                continue

            # Compare with the LAST line of the group, not the whole group:
            # once a second line has started, the next word on that line
            # must still join it.
            line_y0, line_y1 = group["line_y0"], group["line_y1"]

            same_line = abs(span_rect.y0 - line_y0) <= TEXT_LINE_VERTICAL_TOLERANCE

            # Next line of the SAME comment: it follows at normal line
            # spacing. A gap of about a full line or more starts a new
            # comment ("...& Cover" / "SS304 Thrust Collar Considered").
            font_size = float(span.get("size") or 10.0)

            next_line = abs(span_rect.y0 - line_y1) <= min(
                TEXT_GROUP_DISTANCE, max(4.0, 0.9 * font_size)
            )

            horizontal_relation = not (
                span_rect.x1 < group_rect.x0 - 20 or span_rect.x0 > group_rect.x1 + 100
            )

            if horizontal_relation and (same_line or next_line):

                group["spans"].append(span)

                group["rect"] = group_rect | span_rect

                if same_line:
                    group["line_y1"] = max(group["line_y1"], span_rect.y1)
                else:
                    group["line_y0"], group["line_y1"] = span_rect.y0, span_rect.y1

                added = True

                break

        if not added:

            groups.append(
                {
                    "spans": [span],
                    "rect": pymupdf.Rect(span["rect"]),
                    "color": span.get("color"),
                    "line_y0": span["rect"].y0,
                    "line_y1": span["rect"].y1,
                }
            )

    results = []

    for group in groups:

        group_spans = sorted(
            group["spans"],
            key=lambda item: (round(item["rect"].y0, 1), item["rect"].x0),
        )

        text_parts = []

        for span in group_spans:

            value = span["text"].strip()

            if value:
                text_parts.append(value)

        combined_text = " ".join(text_parts)

        combined_text = re.sub(r"\s+", " ", combined_text).strip()

        if combined_text:

            results.append({"text": combined_text, "rect": group["rect"]})

    return results


# ============================================================
# EXTRACT NATIVE ANNOTATIONS
# ============================================================


def extract_native_annotations(page, page_number, records, record_id):

    annotation_xrefs = []

    try:

        for annotation in page.annots() or []:

            annotation_xrefs.append(annotation.xref)

    except Exception:

        return record_id

    for xref in annotation_xrefs:

        try:

            annotation = page.load_annot(xref)

            if annotation is None:
                continue

            info = annotation.info or {}

            # =================================================
            # ANNOTATION TYPE
            # =================================================

            annotation_type = annotation.type

            if isinstance(annotation_type, (tuple, list)) and len(annotation_type) > 1:

                annotation_type_name = annotation_type[1]

            else:

                annotation_type_name = str(annotation_type)

            if annotation_type_name not in ALLOWED_ANNOTATION_TYPES:

                continue

            # AutoCAD drawing text / hidden annotations are not comments.
            if is_cad_or_hidden_annotation(annotation, info):

                continue

            # =================================================
            # AUTHOR
            # =================================================

            author = info.get("title") or info.get("author") or None

            # =================================================
            # NORMAL COMMENT CONTENT
            # =================================================

            content = (info.get("content") or "").strip()

            # =================================================
            # FREETEXT
            # =================================================

            if annotation_type_name == "FreeText":

                # If content is empty, read visible text.
                if not content:

                    try:

                        annotation_text = annotation.get_text("text")

                        if annotation_text:

                            content = annotation_text.strip()

                    except Exception:

                        pass

            # =================================================
            # HIGHLIGHT
            # =================================================
            #
            # IMPORTANT:
            #
            # For Highlight we want the text underneath the
            # highlight, not only info["content"].
            #
            # Therefore always attempt geometric extraction.
            # =================================================

            elif annotation_type_name in TEXT_MARKUP_TYPES:

                highlighted_text = extract_highlight_text(page, annotation)

                if highlighted_text:

                    content = highlighted_text

            # =================================================
            # STAMP
            # =================================================

            elif annotation_type_name == "Stamp":

                if not content:

                    stamp_name = info.get("name")

                    if stamp_name:

                        content = str(stamp_name).strip()

            # =================================================
            # STICKY NOTES AND COMMENTED SHAPES
            # =================================================
            #
            # A sticky note's comment is its "content". A shape
            # (rectangle, cloud, arrow...) is only a comment when
            # the reviewer typed something on it.
            # =================================================

            if not content and (
                annotation_type_name in COMMENT_ONLY_TYPES
                or annotation_type_name == "Text"
            ):

                continue

            type_label = ANNOTATION_TYPE_LABELS.get(
                annotation_type_name, annotation_type_name
            )

            # A reply to another comment ("In reply to").
            try:

                if annotation_type_name == "Text" and annotation.irt_xref > 0:

                    type_label = "Reply"

            except Exception:

                pass

            # =================================================
            # ANNOTATION RECT
            # =================================================

            try:

                annotation_rect = pymupdf.Rect(annotation.rect)

            except Exception:

                annotation_rect = None

            # =================================================
            # DATES
            # =================================================

            created_date, created_time = parse_pdf_datetime(info.get("creationDate"))

            modified_date, modified_time = parse_pdf_datetime(info.get("modDate"))

            # =================================================
            # DUPLICATE CHECK
            # =================================================

            if is_duplicate_record(records, page_number, content, annotation_rect):

                continue

            # =================================================
            # ADD RECORD
            # =================================================

            records.append(
                {
                    "record_id": record_id,
                    "page_number": page_number,
                    "object_type": "Annotation",
                    "annotation_type": type_label,
                    "author": author,
                    "created_date": created_date,
                    "created_time": created_time,
                    "modified_date": modified_date,
                    "modified_time": modified_time,
                    "text": content,
                    "_rect": annotation_rect,
                }
            )

            record_id += 1

        except Exception:

            pass

    return record_id


# ============================================================
# EXTRACT COLOURED / FLATTENED COMMENTS
# ============================================================


def extract_colored_page_comments(page, page_number, records, record_id):
    """
    Extract genuinely flattened coloured review comments.

    Priority:
        1. Native FreeText / Highlight / Stamp are already extracted
           in PASS 1.
        2. PASS 2 should capture only coloured page-content comments
           that are NOT already represented by native annotations.
        3. Prevent a coloured text group from being exported when it
           contains or overlaps an existing native FreeText comment.
    """

    # ============================================================
    # GET COLOURED TEXT SPANS
    # ============================================================

    colored_spans = get_colored_text_spans(page)

    # ============================================================
    # DROP TEXT THAT SITS INSIDE A NATIVE COMMENT BOX
    #
    # Re-reviewed drawings often carry the previous round's comments
    # printed into the page AND the same comments as live annotations.
    # A coloured span inside a native FreeText box is that comment, not
    # a new one. Removing it before grouping also stops two comments from
    # being glued into one long record.
    # ============================================================

    native_rects = [
        existing["_rect"]
        for existing in records
        if existing.get("page_number") == page_number
        and existing.get("object_type") == "Annotation"
        and existing.get("annotation_type") == "FreeText"
        and existing.get("_rect") is not None
    ]

    # PyMuPDF also reports the text DRAWN BY annotations (a red "APPROVED"
    # stamp, a text box) as page text. That is the annotation, not
    # flattened page content, so text inside any annotation that draws
    # its own content is ignored too - including types that are not
    # exported (Stamp, shapes, form fields).
    try:

        for annotation in page.annots() or []:

            if annotation.type[1] in TRANSPARENT_ANNOTATION_TYPES:
                continue

            native_rects.append(pymupdf.Rect(annotation.rect))

    except Exception:

        pass

    if native_rects:

        def inside_native(span_rect):
            centre = pymupdf.Point(
                (span_rect.x0 + span_rect.x1) / 2, (span_rect.y0 + span_rect.y1) / 2
            )
            return any(
                pymupdf.Rect(r.x0 - 3, r.y0 - 3, r.x1 + 3, r.y1 + 3).contains(centre)
                for r in native_rects
            )

        colored_spans = [s for s in colored_spans if not inside_native(s["rect"])]

    # ============================================================
    # GROUP COLOURED TEXT
    # ============================================================

    grouped_comments = group_colored_spans(colored_spans)

    # ============================================================
    # PROCESS EACH COLOURED GROUP
    # ============================================================

    for comment in grouped_comments:

        content = comment.get("text", "").strip()

        rect = comment.get("rect")

        if not content:
            continue

        if len(content) < 2:
            continue

        normalized_colored = normalize_text(content)

        if not normalized_colored:
            continue

        # ========================================================
        # IMPORTANT:
        # CHECK AGAINST NATIVE FREETEXT COMMENTS
        # ========================================================

        belongs_to_native_freetext = False

        for existing in records:

            # Same page only.
            if existing.get("page_number") != page_number:
                continue

            # We specifically want to protect native FreeText.
            if existing.get("object_type") != "Annotation":
                continue

            if existing.get("annotation_type") != "FreeText":
                continue

            existing_text = normalize_text(existing.get("text", ""))

            if not existing_text:
                continue

            # ----------------------------------------------------
            # CASE 1:
            # Exact same text
            # ----------------------------------------------------

            if normalized_colored == existing_text:

                belongs_to_native_freetext = True

                break

            # ----------------------------------------------------
            # CASE 2:
            # Coloured group contains an entire native comment.
            #
            # Example:
            #
            # coloured group:
            # "Provide sunshade... Typical comment..."
            #
            # native:
            # "Provide sunshade..."
            #
            # This means the grouping joined native comments.
            # Do NOT export the combined flattened record.
            # ----------------------------------------------------

            if len(existing_text) >= 8 and existing_text in normalized_colored:

                belongs_to_native_freetext = True

                break

            # ----------------------------------------------------
            # CASE 3:
            # Native FreeText contains this coloured text.
            # ----------------------------------------------------

            if len(normalized_colored) >= 8 and normalized_colored in existing_text:

                belongs_to_native_freetext = True

                break

            # ----------------------------------------------------
            # CASE 4:
            # POSITIONAL CHECK
            #
            # Native FreeText can sometimes differ slightly from
            # page-content text because of spaces / line wrapping.
            # If their rectangles overlap strongly, treat the
            # coloured text as belonging to native FreeText.
            # ----------------------------------------------------

            existing_rect = existing.get("_rect")

            if rect is not None and existing_rect is not None:

                try:

                    intersection = rect & existing_rect

                    if intersection.width > 0 and intersection.height > 0:

                        colored_area = rect.width * rect.height

                        intersection_area = intersection.width * intersection.height

                        if colored_area > 0:

                            overlap_ratio = intersection_area / colored_area

                            # 50% of coloured group falls inside
                            # the native FreeText annotation.
                            if overlap_ratio >= 0.50:

                                belongs_to_native_freetext = True

                                break

                except Exception:
                    pass

        # ========================================================
        # DON'T EXPORT NATIVE FREETEXT AGAIN
        # ========================================================

        if belongs_to_native_freetext:
            continue

        # ========================================================
        # NORMAL DUPLICATE CHECK
        # ========================================================

        if is_duplicate_record(records, page_number, content, rect):

            continue

        # ========================================================
        # THIS IS GENUINE FLATTENED PAGE CONTENT
        # ========================================================

        records.append(
            {
                "record_id": record_id,
                "page_number": page_number,
                "object_type": "Page Content",
                "annotation_type": "FlattenedText",
                "author": None,
                "created_date": None,
                "created_time": None,
                "modified_date": None,
                "modified_time": None,
                "text": content,
                "_rect": rect,
            }
        )

        record_id += 1

    return record_id


# ============================================================
# EXTRACT COMMENTS FROM SCANNED PAGES (OCR)
# ============================================================


def extract_scanned_page_comments(
    page,
    page_number,
    records,
    record_id,
    comments=None,
    annotation_type="ScannedText (OCR)",
):
    """
    OCR the coloured review ink on a scanned (image-only) page.

    Comments already captured as native annotations are skipped.
    """

    if comments is None:
        comments = ocr_scanned.extract_scanned_comments(page)

    for comment in comments:

        content = comment["text"].strip()
        rect = comment["rect"]

        normalized = normalize_text(content)

        if not normalized:
            continue

        already_native = False

        for existing in records:

            if existing.get("page_number") != page_number:
                continue

            if existing.get("object_type") != "Annotation":
                continue

            existing_text = normalize_text(existing.get("text"))

            if existing_text and (
                existing_text == normalized
                or (len(existing_text) >= 8 and existing_text in normalized)
                or (len(normalized) >= 8 and normalized in existing_text)
            ):
                already_native = True
                break

            existing_rect = existing.get("_rect")

            if existing_rect is not None and rect.get_area() > 0:
                overlap = rect & existing_rect

                if (
                    overlap.width > 0
                    and overlap.height > 0
                    and (overlap.width * overlap.height) / rect.get_area() >= 0.5
                ):
                    already_native = True
                    break

        if already_native:
            continue

        if is_duplicate_record(records, page_number, content, rect):
            continue

        records.append(
            {
                "record_id": record_id,
                "page_number": page_number,
                "object_type": "Scanned Content",
                "annotation_type": annotation_type,
                "author": None,
                "created_date": None,
                "created_time": None,
                "modified_date": None,
                "modified_time": None,
                "text": content,
                "_rect": rect,
            }
        )

        record_id += 1

    return record_id


# ============================================================
# EXTRACT FLATTENED CALLOUT COMMENTS (VECTOR SHAPES)
# ============================================================

# A flattened callout is kept only when it reads like a written comment:
# at least this many real words (2+ letters, no digits).
CALLOUT_MIN_WORDS = 3

# A callout whose writing is at least this share coloured (not black) is
# always a comment, whatever its length.
CALLOUT_COLOURED_TEXT_SHARE = 0.5

_WORD_RE = re.compile(r"^[A-Za-z][A-Za-z'’]+[.,:;?!)]*$")


def looks_like_sentence(text):
    """'Specify groove no. & details' -> True; '±1.6', '165-PSV-222A' -> False."""

    words = [token.strip("(\"'") for token in str(text).split()]

    return sum(1 for word in words if _WORD_RE.match(word)) >= CALLOUT_MIN_WORDS


def overlap_fraction(rect, other):
    """Share of `rect` covered by `other` (0..1)."""

    try:
        area = rect.width * rect.height

        if area <= 0:
            return 0.0

        common = rect & other

        if common.is_empty:
            return 0.0

        return (common.width * common.height) / area

    except Exception:
        return 0.0


def extract_callout_page_comments(page, page_number, records, record_id, state):
    """
    Comments flattened into plain drawing shapes: a filled box with a
    coloured border (typical review "callout"). These have no annotation
    object and frequently no text layer, so the box is read directly or
    OCR-ed.
    """

    native_rects = [
        existing["_rect"]
        for existing in records
        if existing.get("page_number") == page_number
        and existing.get("object_type") == "Annotation"
        and existing.get("_rect") is not None
    ]

    # Boxes under ANY live markup (a text box, or a reviewer's rectangle /
    # oval drawn around an old callout) are skipped before OCR. Highlights
    # and links don't count: they draw no content of their own.
    skip_rects = list(native_rects)

    try:

        for annotation in page.annots() or []:

            if annotation.type[1] in TRANSPARENT_ANNOTATION_TYPES:
                continue

            if is_cad_or_hidden_annotation(annotation, annotation.info or {}):
                continue

            skip_rects.append(pymupdf.Rect(annotation.rect))

    except Exception:

        pass

    for comment in ocr_scanned.extract_callout_comments(
        page, state, exclude_rects=skip_rects
    ):

        content = comment["text"].strip()
        rect = comment["rect"]

        if not normalize_text(content):
            continue

        # A box written in colour (blue / red callout text) is a reviewer's
        # comment, however short ("LT-210407,LT-210411",
        # "Haz.Area Class Ex-Certification"). A box with BLACK text is kept
        # only if it reads as a sentence: short black labels ("±1.6",
        # "165-PSV-222A") are drawing text highlighted in an earlier round.
        coloured = comment.get("coloured_text", 0.0) >= CALLOUT_COLOURED_TEXT_SHARE

        if not coloured and not looks_like_sentence(content):
            continue

        # The same comment already exists as a live annotation.
        if any(overlap_fraction(rect, native) >= 0.3 for native in native_rects):
            continue

        if is_duplicate_record(records, page_number, content, rect):
            continue

        records.append(
            {
                "record_id": record_id,
                "page_number": page_number,
                "object_type": "Callout",
                "annotation_type": "Callout",
                "author": None,
                "created_date": None,
                "created_time": None,
                "modified_date": None,
                "modified_time": None,
                "text": content,
                "_rect": rect,
            }
        )

        record_id += 1

    return record_id


# ============================================================
# COLOURED MARKUP (PEN STROKES, HIGHLIGHT / CLOUD REGIONS)
# ============================================================


def add_markup_records(
    page, page_number, records, record_id, comments, annotation_type, author_field=True
):
    """Append OCR-ed coloured markup (pen strokes or highlighted regions)."""

    for comment in comments:

        content = comment["text"].strip()
        rect = comment["rect"]

        if not normalize_text(content):
            continue

        # Fragments such as "wh" or "|" are OCR noise, not comments.
        if (
            comment.get("method") is not None or annotation_type != "Ink (OCR)"
        ) and len(re.sub(r"[\W_]", "", content)) < 2:
            continue

        if is_duplicate_record(records, page_number, content, rect):
            continue

        records.append(
            {
                "record_id": record_id,
                "page_number": page_number,
                "object_type": "Coloured Markup",
                "annotation_type": annotation_type,
                "author": comment.get("author") if author_field else None,
                "created_date": None,
                "created_time": None,
                "modified_date": None,
                "modified_time": None,
                "text": content,
                "_rect": rect,
            }
        )

        record_id += 1

    return record_id


# ============================================================
# REPEATED PAGE LABELS (headers / footers)
# ============================================================

# Coloured page text that is identical AND in the same place on at least
# this many pages is part of the document template (a red "Internal"
# classification in the footer), not a review comment.
REPEATED_LABEL_MIN_PAGES = 3


def remove_repeated_page_labels(records):

    def position_key(record):
        rect = record.get("_rect")

        if rect is None:
            return None

        return (
            normalize_text(record.get("text")),
            round(rect.x0 / 10),
            round(rect.y0 / 6),
        )

    pages_by_key = {}

    for record in records:

        if record.get("object_type") != "Page Content":
            continue

        key = position_key(record)

        if key is not None:
            pages_by_key.setdefault(key, set()).add(record.get("page_number"))

    repeated = {
        key
        for key, pages in pages_by_key.items()
        if len(pages) >= REPEATED_LABEL_MIN_PAGES
    }

    if not repeated:
        return records

    return [
        record
        for record in records
        if record.get("object_type") != "Page Content"
        or position_key(record) not in repeated
    ]


# ============================================================
# FINAL DUPLICATE REMOVAL
# ============================================================


def remove_final_duplicates(records):

    unique_records = []

    for record in records:

        page_number = record.get("page_number")

        text = record.get("text", "")

        rect = record.get("_rect")

        if is_duplicate_record(unique_records, page_number, text, rect):

            continue

        unique_records.append(record)

    # Re-number Record IDs.
    for index, record in enumerate(unique_records, start=1):

        record["record_id"] = index

    return unique_records


# ============================================================
# REMOVE INTERNAL VALUES
# ============================================================


def clean_internal_fields(records):

    cleaned_records = []

    for record in records:

        clean_record = dict(record)

        clean_record.pop("_rect", None)

        cleaned_records.append(clean_record)

    return cleaned_records


# ============================================================
# MAIN PDF EXTRACTION
# ============================================================


def extract_pdf(pdf_path, scanned_text_mode="auto", coloured_markup=True):
    """
    Extract every review comment from one PDF.

    scanned_text_mode controls how scanned (image-only) pages are read:
        "auto" - read the whole page only when it is a typed comment
                 sheet with numbered points; otherwise coloured ink only
        "all"  - read all text on every scanned page
        "off"  - coloured ink only

    coloured_markup also reads pen (Ink) strokes and coloured highlight /
    cloud regions that carry no annotation text.

    Returns {"summary": {...}, "records": [...]}.
    """

    records = []

    with pymupdf.open(pdf_path) as document:

        summary = {
            "pages": len(document),
            "annotations": 0,
            "scanned_pages": 0,
            "text_sheet_pages": 0,
            "callouts": 0,
            "ink_marks": 0,
            "highlight_regions": 0,
            "ocr_available": ocr_scanned.ocr_available(),
            "ocr_error": ocr_scanned.ocr_error(),
        }

        record_id = 1

        callout_state = {}

        # ====================================================
        # PAGE LOOP
        # ====================================================

        for page_number in range(1, len(document) + 1):

            page = document.load_page(page_number - 1)

            # =================================================
            # PASS 1
            # NATIVE ANNOTATIONS
            # =================================================

            record_id = extract_native_annotations(
                page, page_number, records, record_id
            )

            # =================================================
            # PASS 2
            # FLATTENED COLOURED TEXT
            # =================================================

            record_id = extract_colored_page_comments(
                page, page_number, records, record_id
            )

            # =================================================
            # PASS 2B
            # SCANNED PAGES (OCR)
            #
            #   typed comment sheet -> read the whole page, one
            #                          record per numbered point
            #   drawing / form      -> read only the coloured ink
            #                          (red, orange, gold, green, blue)
            # =================================================

            if ocr_scanned.is_scanned_page(page):

                summary["scanned_pages"] += 1

                if not summary["ocr_available"]:

                    pass

                else:

                    mode = (scanned_text_mode or "auto").lower()

                    sheet_comments = []

                    if mode == "all":

                        sheet_comments = ocr_scanned.extract_text_sheet_comments(page)

                    elif mode == "auto" and ocr_scanned.is_text_sheet(page):

                        # Only accepted when numbered points are found.
                        sheet_comments = ocr_scanned.extract_text_sheet_comments(
                            page, require_points=True
                        )

                    if sheet_comments:

                        summary["text_sheet_pages"] += 1

                        record_id = extract_scanned_page_comments(
                            page,
                            page_number,
                            records,
                            record_id,
                            comments=sheet_comments,
                            annotation_type="TypedText (OCR)",
                        )

                    else:

                        record_id = extract_scanned_page_comments(
                            page, page_number, records, record_id
                        )

            # =================================================
            # PASS 2C
            # FLATTENED CALLOUT BOXES (vector shapes)
            # =================================================

            before = len(records)

            record_id = extract_callout_page_comments(
                page, page_number, records, record_id, callout_state
            )

            summary["callouts"] += len(records) - before

            if not coloured_markup or not summary["ocr_available"]:
                continue

            # =================================================
            # PASS 2D
            # PEN (INK) STROKES
            # =================================================

            if EXTRACT_PEN_MARKS:

                before = len(records)

                record_id = add_markup_records(
                    page,
                    page_number,
                    records,
                    record_id,
                    ocr_scanned.extract_ink_comments(page),
                    "Ink (OCR)",
                )

                summary["ink_marks"] += len(records) - before

            # =================================================
            # PASS 2E
            # HIGHLIGHT / CLOUD REGIONS ON NORMAL PAGES
            # (scanned pages are handled by the ink pass above)
            # =================================================

            if not EXTRACT_HIGHLIGHT_REGIONS or ocr_scanned.is_scanned_page(page):
                continue

            before = len(records)

            exclude = [
                record["_rect"]
                for record in records
                if record["page_number"] == page_number
                and record.get("_rect") is not None
            ]

            record_id = add_markup_records(
                page,
                page_number,
                records,
                record_id,
                ocr_scanned.extract_highlight_comments(page, exclude_rects=exclude),
                "Highlight (OCR)",
                author_field=False,
            )

            summary["highlight_regions"] += len(records) - before

        # ====================================================
        # PASS 3
        # DUPLICATES
        # ====================================================

        records = remove_repeated_page_labels(records)

        records = remove_final_duplicates(records)

        summary["annotations"] = len(records)

        # Remove _rect before sending data to frontend/Excel.
        records = clean_internal_fields(records)

    # ========================================================
    # FINAL DEBUG
    # ========================================================

    return {"summary": summary, "records": records}